-- 4. CART_ITEMS
----------------------------
CREATE TABLE ADMIN.CART_ITEMS (
    CART_ITEM_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    CART_ID      NUMBER NOT NULL,
    ARTICLE_ID   VARCHAR2(30) NOT NULL,

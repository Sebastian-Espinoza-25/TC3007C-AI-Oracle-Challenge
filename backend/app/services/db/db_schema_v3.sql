    CONSTRAINT CK_CART_ITEMS_QTY_POS CHECK (quantity > 0),
    CONSTRAINT CK_CART_ITEMS_PRICE_NONNEG CHECK (price >= 0),
    CONSTRAINT FK_CART_ITEMS_CART FOREIGN KEY (CART_ID)

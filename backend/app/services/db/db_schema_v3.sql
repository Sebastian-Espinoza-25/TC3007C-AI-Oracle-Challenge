-- 10. PRODUCT_RATINGS
----------------------------
CREATE TABLE ADMIN.PRODUCT_RATINGS (
    RATING_ID    NUMBER GENERATED ALWAYS AS IDENTITY,
    USER_ID      NUMBER NOT NULL,
    ARTICLE_ID   VARCHAR2(30) NOT NULL,
    RATING       NUMBER(1) NOT NULL,
    REVIEW_TEXT  CLOB,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_PRODUCT_RATINGS PRIMARY KEY (RATING_ID),
    CONSTRAINT UQ_PR_USER_ARTICLE UNIQUE (USER_ID, ARTICLE_ID),
    CONSTRAINT CK_PR_RATING CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT FK_PR_USER FOREIGN KEY (USER_ID)
        REFERENCES ADMIN.APP_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PR_ARTICLE FOREIGN KEY (ARTICLE_ID)
        REFERENCES ADMIN.CATALOG(EXTERNAL_ARTICLE_ID) ON DELETE CASCADE
);

CREATE INDEX IX_PR_USER    ON ADMIN.PRODUCT_RATINGS(USER_ID);
CREATE INDEX IX_PR_ARTICLE ON ADMIN.PRODUCT_RATINGS(ARTICLE_ID);


CREATE OR REPLACE TRIGGER ADMIN.TRG_PRODUCT_RATINGS_UPD_TS
BEFORE UPDATE ON ADMIN.PRODUCT_RATINGS
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/



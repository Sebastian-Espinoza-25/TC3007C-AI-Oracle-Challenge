CREATE INDEX IX_CART_ITEMS_CART    ON ADMIN.CART_ITEMS (CART_ID);
CREATE INDEX IX_CART_ITEMS_ARTICLE ON ADMIN.CART_ITEMS (ARTICLE_ID);



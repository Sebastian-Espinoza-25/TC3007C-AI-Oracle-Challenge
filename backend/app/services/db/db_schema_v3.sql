);

CREATE INDEX IX_ORDERS_USER ON ADMIN.ORDERS (USER_ID);
CREATE INDEX IX_ORDERS_PAYM ON ADMIN.ORDERS (SYS_EXTRACT_UTC(PAYMENT_DATE));


